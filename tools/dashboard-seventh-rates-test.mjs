import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';

const path = 'apps/ferricstore_server/lib/ferricstore_server/health/dashboard/render/recent_rates.js';
const source = fs.readFileSync(path, 'utf8');
const window = {};
vm.runInNewContext(source, {window, document: {addEventListener() {}, querySelector() { return null; }}});
const reduce = window.dashboardRecentRates.reduce;
const sample = (at, commands, extra = {}) => ({at, commands: String(commands), hits: '10', misses: '2', cold: '1', expired: '0', evicted: '0', run: 'a', sampleRate: '100', ...extra});
let state = reduce(null, sample(1000, '9007199254740993'));
assert.equal(state.status, 'warming');
state = reduce(state, sample(3000, '9007199254740997'));
assert.equal(state.rates.commands, 2);
assert.equal(state.elapsedMs, 2000);
assert.equal(state.rates.hits, 0);
assert.equal(reduce(state, sample(2000, '9007199254740999')).status, 'warming');
assert.equal(reduce(state, sample(4000, '1')).status, 'warming');
assert.equal(reduce(state, sample(4000, '9007199254740999', {run: 'b'})).status, 'warming');
assert.equal(reduce(state, sample(4000, '9007199254740999', {sampleRate: '1'})).status, 'warming');
assert.equal(reduce(state, sample(20000, '9007199254740999')).status, 'warming');
assert.equal(reduce(state, sample(4000, 'invalid')).status, 'unavailable');
state = null;
for (let i = 0; i < 1000; i++) state = reduce(state, sample(i * 2000, i * 4));
assert.ok(state.samples.length <= 31);
assert.ok(state.elapsedMs <= 60000);
assert.equal(state.rates.commands, 2);
assert.ok(!/setInterval|fetch\(|localStorage|sessionStorage/.test(source));
console.log('Recent rate bounds, exact integer deltas, resets, gaps and missing data passed.');
